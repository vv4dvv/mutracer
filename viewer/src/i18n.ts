export function translate(lang: Lang, text: string, vars?: Record<string, string | number>) {
  const template = lang === 'en' ? text : ZH[text] ?? text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Translator for the current interface language. Re-renders when the language changes. */
export function useT() {
  const lang = useViewer((state) => state.ui.lang);
  return useCallback((text: string, vars?: Record<string, string | number>) => translate(lang, text, vars), [lang]);
}

/** Translator for code outside React components (event handlers, engine callbacks). */
export function t(text: string, vars?: Record<string, string | number>) {
  return translate(useViewer.getState().ui.lang, text, vars);
}
